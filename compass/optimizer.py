"""
PRISM — compass/optimizer.py
DSPy Closed-Loop Workflow Optimizer

PRISM doesn't just measure. It learns and improves.

COMPASS uses VERDICT scores from live sessions to
automatically optimize the prompt architecture driving
AI agent behavior in a workflow.

If groundedness is declining  → rewrite retrieval prompt
If influence survival is low  → adjust uncertainty expression
If novelty delta is plateauing → push toward distant associations
If calibration is drifting    → tighten confidence language

Closed-loop. Evidence-driven. Client-specific.

This turns PRISM from an observability tool into a
self-improving deployment system.

The feature that signals you understand the full
FDE lifecycle — not just deployment, but continuous
improvement.
"""

